CREATE SCHEMA IF NOT EXISTS fin;

-- 1. Extend existing fiscal_period table safely

ALTER TABLE fin.fiscal_period
    ADD COLUMN IF NOT EXISTS period VARCHAR(7);

ALTER TABLE fin.fiscal_period
    ADD COLUMN IF NOT EXISTS opened_at TIMESTAMPTZ;

ALTER TABLE fin.fiscal_period
    ADD COLUMN IF NOT EXISTS opened_by VARCHAR(100);

ALTER TABLE fin.fiscal_period
    ADD COLUMN IF NOT EXISTS locked_at TIMESTAMPTZ;

ALTER TABLE fin.fiscal_period
    ADD COLUMN IF NOT EXISTS locked_by VARCHAR(100);

ALTER TABLE fin.fiscal_period
    ADD COLUMN IF NOT EXISTS remarks TEXT;

-- 2. Populate period from existing year and month

UPDATE fin.fiscal_period
SET period = year::TEXT || '-' || LPAD(month::TEXT, 2, '0')
WHERE period IS NULL OR BTRIM(period) = '';

UPDATE fin.fiscal_period
SET opened_at = COALESCE(opened_at, now())
WHERE opened_at IS NULL;

ALTER TABLE fin.fiscal_period
    ALTER COLUMN period SET NOT NULL;

ALTER TABLE fin.fiscal_period
    ALTER COLUMN opened_at SET DEFAULT now();

ALTER TABLE fin.fiscal_period
    ALTER COLUMN opened_at SET NOT NULL;

-- 3. Validate period dates

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'fin.fiscal_period'::regclass
          AND conname = 'ck_fin_fiscal_period_dates'
    ) THEN
        ALTER TABLE fin.fiscal_period
            ADD CONSTRAINT ck_fin_fiscal_period_dates
            CHECK (
                start_date <= end_date
                AND period =
                    year::TEXT || '-' || LPAD(month::TEXT, 2, '0')
            );
    END IF;
END $$;

-- 4. Unique period index
-- Existing unique key (tenant_id, company_id, year, month)
-- remains unchanged.

CREATE UNIQUE INDEX IF NOT EXISTS
    uq_fin_fiscal_period_tenant_company_period
ON fin.fiscal_period(tenant_id, company_id, period);

CREATE INDEX IF NOT EXISTS
    ix_fin_fiscal_period_status
ON fin.fiscal_period(company_id, status, period);

-- 5. Synchronize inventory period controls
-- Preserve existing CLOSED / LOCKED states.
-- Do not copy inventory closed_by VARCHAR into legacy BIGINT.

INSERT INTO fin.fiscal_period AS fp (
    tenant_id,
    company_id,
    year,
    month,
    period,
    start_date,
    end_date,
    status,
    opened_at,
    closed_at,
    remarks
)
SELECT
    ipc.tenant_id,
    ipc.company_id,
    SPLIT_PART(ipc.period, '-', 1)::INTEGER,
    SPLIT_PART(ipc.period, '-', 2)::INTEGER,
    ipc.period,
    TO_DATE(ipc.period || '-01', 'YYYY-MM-DD'),
    (
        TO_DATE(ipc.period || '-01', 'YYYY-MM-DD')
        + INTERVAL '1 month'
        - INTERVAL '1 day'
    )::DATE,
    CASE
        WHEN UPPER(ipc.status) = 'LOCKED' THEN 'LOCKED'
        WHEN UPPER(ipc.status) = 'CLOSED' THEN 'CLOSED'
        ELSE 'OPEN'
    END,
    COALESCE(ipc.opened_at, now()),
    ipc.closed_at,
    ipc.remarks
FROM inv.inventory_period_control ipc
WHERE ipc.period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'

ON CONFLICT (tenant_id, company_id, year, month)
DO UPDATE SET

    status = CASE
        WHEN UPPER(COALESCE(fp.status, 'OPEN')) = 'LOCKED'
          OR UPPER(COALESCE(EXCLUDED.status, 'OPEN')) = 'LOCKED'
            THEN 'LOCKED'

        WHEN UPPER(COALESCE(fp.status, 'OPEN')) = 'CLOSED'
          OR UPPER(COALESCE(EXCLUDED.status, 'OPEN')) = 'CLOSED'
            THEN 'CLOSED'

        ELSE COALESCE(fp.status, EXCLUDED.status, 'OPEN')
    END,

    closed_at = COALESCE(
        fp.closed_at,
        EXCLUDED.closed_at
    ),

    remarks = COALESCE(
        fp.remarks,
        EXCLUDED.remarks
    );

-- 6. Central fiscal period audit table

CREATE TABLE IF NOT EXISTS fin.fiscal_period_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fiscal_period_id BIGINT NOT NULL
        REFERENCES fin.fiscal_period(id),

    tenant_id BIGINT NOT NULL,
    company_id BIGINT NOT NULL,

    period VARCHAR(7) NOT NULL,

    action VARCHAR(20) NOT NULL
        CHECK (
            action IN (
                'GENERATE',
                'CLOSE',
                'REOPEN',
                'LOCK'
            )
        ),

    old_status VARCHAR(10),
    new_status VARCHAR(10) NOT NULL,

    reason TEXT NOT NULL,

    performed_by VARCHAR(100) NOT NULL,

    performed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS
    ix_fin_fp_audit_period
ON fin.fiscal_period_audit(
    company_id,
    period,
    performed_at DESC
);


CREATE TABLE core.menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES core.menu(id) ON DELETE CASCADE,
    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    path VARCHAR(255),
    icon VARCHAR(100),
    sort_order INT NOT NULL DEFAULT 0,
    is_header BOOLEAN NOT NULL DEFAULT FALSE,
    required_permission VARCHAR(80),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_menu_parent ON core.menu(parent_id, sort_order);
CREATE INDEX idx_menu_status ON core.menu(status) WHERE status = 'ACTIVE';

